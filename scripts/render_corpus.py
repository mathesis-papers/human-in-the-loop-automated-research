#!/usr/bin/env python3
"""Render the versioned public output inventory without bibliography citations."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def tex(text):
    # Keep the primary title's existing inline mathematical notation.
    replacements = {"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_",
                    "á": r"\'{a}", "é": r"\'{e}", "í": r"\'{i}", "î": r"\^{i}",
                    "ó": r"\'{o}", "ú": r"\'{u}", "Á": r"\'{A}"}
    return "".join(replacements.get(c, c) for c in text)


def main():
    papers = json.loads((ROOT / "data/collaborative-arxiv.json").read_text())["papers"]
    rows = [r"% Generated by scripts/render_corpus.py; edit the JSON manifest.",
            r"\begin{table}[htbp]\centering\small",
            r"\caption{Public output inventory, with exact arXiv versions.}\label{tab:corpus}",
            r"\begin{tabularx}{\linewidth}{@{}L{0.23\linewidth}Y@{}}",
            r"\toprule Version and field & Work and reported scope \\",
            r"\midrule"]
    ordered = sorted(papers, key=lambda item: item["arxiv_id"])
    for i, p in enumerate(ordered):
        if i == 9:
            rows.extend([r"\bottomrule\end{tabularx}\end{table}",
                         r"\begin{table}[htbp]\ContinuedFloat\centering\small",
                         r"\caption{Public output inventory, with exact arXiv versions (continued).}",
                         r"\begin{tabularx}{\linewidth}{@{}L{0.23\linewidth}Y@{}}",
                         r"\toprule Version and field & Work and reported scope \\",
                         r"\midrule"])
        version = f"{p['arxiv_id']}v{p['arxiv_version']}"
        # arXiv's one reversed author record is preserved verbatim in the data,
        # while the inventory table uses the researcher's established name.
        names = ["Zhang, Wenlin" if a == "Wenlin, Zhang" else a
                 for a in p["authors_primary_metadata"]]
        display_authors = ", ".join(
            f"{n.split(', ', 1)[1]} {n.split(', ', 1)[0]}" if ", " in n else n
            for n in names
        )
        rows.append(r"\arxiv{" + version + r"}\par " + tex(p["domain"]) + " & "
                    + tex(p["title"]) + r"\par\emph{" + tex(display_authors) + r"}\par\smallskip "
                    + tex(p["reported_scope"]) + r" \\[8pt]")
    rows.extend([r"\bottomrule\end{tabularx}", r"\end{table}"])
    (ROOT / "paper/corpus-table.tex").write_text("\n".join(rows) + "\n")
    print(f"Rendered {len(papers)} versioned output entries.")


if __name__ == "__main__":
    main()
