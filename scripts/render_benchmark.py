#!/usr/bin/env python3
"""Render the N=30 three-family external benchmark, structural audit, longitudinal
revision subset, and mechanistic ablation + public gate audit tables/figures from JSON."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AXES = [
    ('correctness_rigor', 'Correctness and rigor'),
    ('claim_calibration', 'Claim calibration'),
    ('verification_grounding', 'Verification grounding'),
    ('novelty_significance', 'Novelty and significance'),
    ('literature_attribution', 'Literature attribution'),
    ('clarity_exposition', 'Clarity and exposition'),
    ('overall', 'Overall'),
]
COHORTS = ['autonomous_ai', 'human_only_arxiv', 'human_in_the_loop']
JUDGES = [
    ('codex_gpt61sol', r'Codex (\code{gpt-6.1-sol})', 'Codex (gpt-6.1-sol)'),
    ('claude_opus55', r'Claude (\code{opus-5-5})', 'Claude (opus-5-5)'),
    ('google_gemini', 'Google Gemini', 'Google Gemini'),
]
PAIR_JUDGES = [('codex', 'Judge 1'), ('second_family', 'Judge 2')]
COLORS = ['planegray', 'linkblue', 'reviewgreen']
REVISION_DAYS = {
    'arxiv_fidelity': 41,
    'arxiv_subquorum': 20,
    'arxiv_gaussian': 30,
    'arxiv_eof': 2,
    'arxiv_insertion': 12,
}


def read(name):
    return json.loads((ROOT / 'data/benchmark' / name).read_text())


def longitudinal_rows(data, judge):
    return {r['pair_key']: r for r in data[judge]['rows']
            if r['stratum'].startswith('Stratum 1:')}


def fmt_p(p):
    if p < 0.0001:
        return f"{p:.6f}"
    return f"{p:.4f}"


def main():
    external = read('ext_n30_summary.json')
    paired = read('benchmark_summary.json')

    # --- Table 3: N=30 3-family benchmark + structural audit + longitudinal revisions ---
    rows = [
        r'% Generated by scripts/render_benchmark.py from archived benchmark JSON.',
        r'\begin{table}[htbp]',
        r'\centering\scriptsize',
        r'\setlength{\tabcolsep}{2.2pt}',
        r'\caption{External three-cohort benchmark across three named model families and longitudinal revisions. A: ten-point scores (mean $\pm$ sample SD across ten manuscripts per cohort; 90 blinded evaluations total; Kendall concordance $W=' + f"{external['agreement']['kendall_W_3families_N30']:.3f}" + r'$). B: full-document structure and verification counts ($n=10$ per cohort). C: separate, version-blinded public arXiv revision study (overall scores, changes and elapsed calendar days). AI: autonomous AgentAlphaXiv; H: contemporaneous human-only arXiv; H+AI: human-in-the-loop collaboration.}',
        r'\label{tab:benchmark}',
        r'\textbf{A. Three-family blinded cohort scoring: 30 manuscripts, 90 evaluations ($n=10$ per cohort)}\par\smallskip',
        r'\begin{tabularx}{\linewidth}{@{}Yccccccccc@{}}',
        r'\toprule & \multicolumn{3}{c}{Codex (\code{gpt-6.1-sol})} & \multicolumn{3}{c}{Claude (\code{opus-5-5})} & \multicolumn{3}{c}{Google Gemini} \\',
        r'\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(l){8-10}',
        r'Axis & AI & H & H+AI & AI & H & H+AI & AI & H & H+AI \\ \midrule',
    ]
    for key, label in AXES:
        cells = []
        for jkey, _, _ in JUDGES:
            for cohort in COHORTS:
                s = external['judges'][jkey]['by_cohort'][cohort][key]
                cells.append(f"${s['mean']:.2f}\\pm{s['sd']:.2f}$")
        prefix = r'\textbf{' + label + '}' if key == 'overall' else label
        rows.append(prefix + ' & ' + ' & '.join(cells) + r' \\')
    rows.append(r'\midrule')
    win_cells = []
    for jkey, _, _ in JUDGES:
        comp = external['judges'][jkey]['comparisons']['hitl_vs_ai']
        win_cells.append(
            r'\multicolumn{3}{c}{'
            + f"{comp['wins']}/100 wins; $p={fmt_p(comp['exact_perm_p'])}$"
            + '}'
        )
    rows.append(r'H+AI vs.\ AI (184,756 perm.) & ' + ' & '.join(win_cells) + r' \\')
    rows += [
        r'\bottomrule\end{tabularx}',
        r'\par\vspace{7pt}',
        r'\textbf{B. Full-document structure and verification artifacts ($n=10$ per cohort)}\par\smallskip',
        r'\setlength{\tabcolsep}{4pt}',
        r'\begin{tabularx}{\linewidth}{@{}Yccc@{}}',
        r'\toprule Metric & AI & H & H+AI \\ \midrule',
    ]
    metrics = [
        ('pages_mean', 'Pages, mean (median)', 'pages'),
        ('formal_statements_total', 'Theorem / lemma / proposition blocks, total (mean)', 'pair_stmt'),
        ('proof_blocks_total', 'Proof blocks, total (mean)', 'pair_proof'),
        ('papers_with_formal_verif', 'Papers reporting formal or certified checks', 'fraction'),
        ('formal_verif_mentions_total', 'Verification-related text mentions, total', 'd'),
        ('references_median', 'References, median', 'd'),
    ]
    for key, label, fmt in metrics:
        cells = []
        for cohort in COHORTS:
            s = external['structural'][cohort]
            if fmt == 'fraction':
                cells.append(f"{s[key]}/{s['n']}")
            elif fmt == 'pages':
                cells.append(f"{s['pages_mean']:.1f} ({s['pages_median']:.1f})")
            elif fmt == 'pair_stmt':
                cells.append(f"{s['formal_statements_total']} ({s['formal_statements_mean']:.1f})")
            elif fmt == 'pair_proof':
                cells.append(f"{s['proof_blocks_total']} ({s['proof_blocks_mean']:.1f})")
            else:
                cells.append(format(s[key], fmt))
        rows.append(label + ' & ' + ' & '.join(cells) + r' \\')
    rows += [
        r'\bottomrule\end{tabularx}',
        r'\smallskip',
        r'\begin{minipage}{\linewidth}\scriptsize Verification artifacts in H+AI span Lean~4 proofs, DRAT certificates, 192-bit Arb interval enclosures and exact polynomial, rational or exhaustive certificates across all ten manuscripts. The single formally verified human-only preprint (\arxiv{2611.00153v1}, Lean~4) ranked highest in its cohort under Claude (8.0) and Gemini (9.2) and second under Codex (8.1).\end{minipage}',
        r'\par\vspace{7pt}',
        r'\textbf{C. Longitudinal external collaboration: public v1$\to$vK}\par\smallskip',
        r'\begin{tabularx}{\linewidth}{@{}Yccccc@{}}',
        r'\toprule & & \multicolumn{2}{c}{Judge 1} & \multicolumn{2}{c}{Judge 2} \\',
        r'\cmidrule(lr){3-4}\cmidrule(l){5-6}',
        r'arXiv ID and versions & Days & v1 $\to$ vK & $\Delta$ & v1 $\to$ vK & $\Delta$ \\ \midrule',
    ]
    by_judge = {j: longitudinal_rows(paired, j) for j, _ in PAIR_JUDGES}
    for key in ['arxiv_gaussian', 'arxiv_fidelity', 'arxiv_subquorum', 'arxiv_eof', 'arxiv_insertion']:
        record = by_judge['codex'][key]
        identity, versions = record['label_desc'].removeprefix('arXiv:').split(' (')
        label = r'\arxiv{' + identity + '} ' + versions.rstrip(')').replace(' -> ', r'$\to$')
        cells = [str(REVISION_DAYS[key])]
        for judge, _ in PAIR_JUDGES:
            r = by_judge[judge][key]
            delta = r['delta']['overall']
            dstr = "0.0" if abs(delta) < 1e-9 else f"{delta:+.1f}"
            cells += [f"${r['before']['overall']:.1f}\\to{r['after']['overall']:.1f}$", f"${dstr}$"]
        rows.append(label + ' & ' + ' & '.join(cells) + r' \\')
    rows += [
        r'\bottomrule\end{tabularx}',
        r'\smallskip',
        r'\begin{minipage}{\linewidth}\scriptsize The final two rows are minor-edit negative controls. Panels A and C use separate scoring contexts; their absolute scores are not interchangeable.\end{minipage}',
        r'\end{table}',
    ]
    (ROOT / 'paper/benchmark-table.tex').write_text('\n'.join(rows) + '\n')

    # --- Figure 3: 3-panel N=30 TikZ figure ---
    fig = [
        r'% Generated by scripts/render_benchmark.py; coordinates are archived JSON scores.',
        r'\begin{figure}[htbp]',
        r'\centering',
        r'\begin{tikzpicture}[font=\small]',
        r'\node[anchor=west,font=\bfseries] at (-0.55,6.85) {a\quad Overall scores across three independent model families ($n=10$ per cohort)};',
    ]
    for ji, (jkey, _, plain_title) in enumerate(JUDGES):
        xshift = ji * 5.35
        fig.append(f'\\begin{{scope}}[xshift={xshift:.2f}cm,x=0.78cm,y=0.55cm]')
        fig.append(r'\node[font=\footnotesize\bfseries] at (2.8,11.35) {' + plain_title + '};')
        for tick in range(0, 11, 2):
            fig.append(f'\\draw[planegray!18] (0.35,{tick})--(5.55,{tick});')
            if ji == 0:
                fig.append(f'\\node[anchor=east,font=\\scriptsize] at (0.22,{tick}) {{{tick}}};')
        for ci, cohort in enumerate(COHORTS):
            x = 1.05 + ci * 1.75
            color = COLORS[ci]
            values = sorted(r['scores']['overall'] for r in external['judges'][jkey]['per_paper'] if r['cohort'] == cohort)
            s = external['judges'][jkey]['by_cohort'][cohort]['overall']
            for i, val in enumerate(values):
                offset = ((i % 5) - 2) * 0.095 + (0.04 if i >= 5 else -0.04)
                fig.append(f'\\fill[{color}] ({x + offset:.2f},{val:.2f}) circle (1.6pt);')
            bar_x = x + 0.44
            lo = max(0.0, s['mean'] - s['sd'])
            hi = min(10.0, s['mean'] + s['sd'])
            mean = s['mean']
            fig += [
                f'\\draw[{color},thick] ({bar_x:.2f},{lo:.2f})--({bar_x:.2f},{hi:.2f});',
                f'\\draw[{color},thick] ({bar_x-0.09:.2f},{lo:.2f})--({bar_x+0.09:.2f},{lo:.2f}) ({bar_x-0.09:.2f},{hi:.2f})--({bar_x+0.09:.2f},{hi:.2f});',
                f'\\draw[{color},very thick] ({bar_x-0.16:.2f},{mean:.2f})--({bar_x+0.16:.2f},{mean:.2f});',
                f'\\node[font=\\scriptsize,align=center] at ({x+0.15:.2f},-0.85) {{{["AI", "Human", "H+AI"][ci]}}};',
            ]
        fig.append(r'\end{scope}')

    fig.append(r'\node[anchor=west,font=\bfseries] at (-0.55,-1.25) {b\quad Cohort means on the six rubric axes};')
    axis_labels = ['Rigor', 'Calibration', 'Grounding', 'Novelty', 'Attribution', 'Clarity']
    for ji, (jkey, _, _) in enumerate(JUDGES):
        xshift = 1.35 + ji * 4.80
        fig.append(f'\\begin{{scope}}[xshift={xshift:.2f}cm,yshift=-1.85cm,x=0.38cm,y=0.55cm]')
        for tick in range(0, 11, 2):
            fig.append(f'\\draw[planegray!18] ({tick},-5.45)--({tick},0.4);')
            fig.append(f'\\node[below,font=\\scriptsize] at ({tick},-5.55) {{{tick}}};')
        for ai, (key, _) in enumerate(AXES[:6]):
            if ji == 0:
                fig.append(f'\\node[anchor=east,font=\\scriptsize] at (-0.35,{-ai}) {{{axis_labels[ai]}}};')
            for ci, cohort in enumerate(COHORTS):
                mean = external['judges'][jkey]['by_cohort'][cohort][key]['mean']
                fig.append(f'\\fill[{COLORS[ci]}] ({mean:.2f},{-ai+(ci-1)*0.22:.2f}) circle (1.7pt);')
        fig.append(r'\end{scope}')

    for ci, label in enumerate(['Autonomous AI-only (n=10)', 'Human-only arXiv (n=10)', 'Human-in-the-loop arXiv (n=10)']):
        x = 0.25 + ci * 5.05
        fig.append(f'\\fill[{COLORS[ci]}] ({x:.2f},-5.75) circle (2pt);')
        fig.append(f'\\node[anchor=west,font=\\scriptsize] at ({x+0.18:.2f},-5.75) {{{label}}};')

    w_val = external['agreement']['kendall_W_3families_N30']
    fig += [
        r'\end{tikzpicture}',
        r'\caption{Three-cohort external benchmark across three independent model families ($N=30$ public manuscripts, 90 blinded evaluations). Panel a displays every overall score alongside cohort means (thick crossbars) and sample SDs (capped bars) on the full 0--10 scale, showing both the systematic margin over autonomous AI-only studies and the 2.3- to 4.2-fold dispersion compression relative to unverified human preprints (whose low tail reflects two fatal-error papers independently flagged by all three judges). Panel b shows cohort means on each rubric axis. Three-family rank concordance across all 30 manuscripts is Kendall $W=' + f'{w_val:.3f}' + r'$. Dots represent blind manuscript judgments rather than kernel proofs; exact values and permutation tests appear in Table~\ref{tab:benchmark}.}',
        r'\label{fig:benchmark}',
        r'\end{figure}',
    ]
    (ROOT / 'paper/benchmark-figure.tex').write_text('\n'.join(fig) + '\n')

    # --- Table 4: Controlled 20-claim mechanistic ablation + 24,925-PR public gate audit ---
    ab = read('ablation_obligation_threshold.json')
    ga = read('exp3_trureturing_audit.json')
    arm_specs = [
        ('arm1_claude_prose', r'Single-family prose (\code{claude-opus-5-5})'),
        ('arm2_codex_prose', r'Single-family prose (\code{gpt-6.1-sol})'),
        ('arm3_prose_union', r'Cross-family prose union (Claude $\lor$ Codex)'),
        ('arm3b_prose_intersection', r'Cross-family prose intersection (Claude $\land$ Codex)'),
        ('arm4_exec_gate_standalone', r'Executable verification-target gate (standalone)'),
        ('arm5_prose_union_plus_exec_gate', r'\textbf{Prose union + executable obligation gate}'),
    ]
    t4 = [
        r'% Generated by scripts/render_benchmark.py from archived ablation and PR-audit JSON.',
        r'\begin{table}[htbp]',
        r'\centering\footnotesize',
        r"\caption{Mechanistic ablation of review obligations and large-scale public admission-gate audit. A: blinded evaluation on 20 real mathematical propositions (10 flawed claims and 10 matched valid theorems extracted from the collaborative arXiv corpus). Requiring an independently executed counterexample witness eliminates false-positive ``review slop'' (FPR $30\%\to 0\%$). B: public GitHub audit of \gh{the-omega-institute/trureturing}{the-omega-institute/trureturing} queried on 27 November 2026.}",
        r'\label{tab:ablation}',
        r'\textbf{A. Controlled 20-claim ablation: prose review versus executable obligation gate}\par\smallskip',
        r'\begin{tabularx}{\linewidth}{@{}Ycccccc@{}}',
        r'\toprule Review configuration & Recall & FPR (slop) & Precision & F1 & Acc. & Fisher $p$ \\ \midrule',
    ]
    for akey, alabel in arm_specs:
        m = ab['arms'][akey]
        bold = akey == 'arm5_prose_union_plus_exec_gate'
        rec_s = f"{m['TP']}/10 ({m['recall_pct']:.0f}\\%)"
        fpr_s = f"{m['FP']}/10 ({m['fpr_slop_pct']:.0f}\\%)"
        prec_s = f"{m['precision_pct']:.1f}\\%"
        f1_s = f"{m['f1_pct']:.1f}\\%"
        acc_s = f"{m['accuracy_pct']:.1f}\\%"
        p_s = f"${m['fisher_exact_p']:.4f}$" if m['fisher_exact_p'] >= 0.0005 else f"${m['fisher_exact_p']:.6f}$"
        if bold:
            rec_s = r'\textbf{' + rec_s + '}'
            fpr_s = r'\textbf{' + fpr_s + '}'
            prec_s = r'\textbf{' + prec_s + '}'
            f1_s = r'\textbf{' + f1_s + '}'
            acc_s = r'\textbf{' + acc_s + '}'
        t4.append(f"{alabel} & {rec_s} & {fpr_s} & {prec_s} & {f1_s} & {acc_s} & {p_s} " + r'\\')
    t4 += [
        r'\bottomrule\end{tabularx}',
        r'\smallskip',
        r'\begin{minipage}{\linewidth}\scriptsize The single executable-gate miss (\code{ab_17}, Wigner normalization) symbolically computed the exact $1/2$ discrepancy before halting on a strict Python \code{is True} versus SymPy boolean assertion, counted conservatively as a non-detection under zero-intervention execution.\end{minipage}',
        r'\par\vspace{7pt}',
        r'\textbf{B. Public Lean~4 admission-gate throughput and repair audit (\code{the-omega-institute/trureturing})}\par\smallskip',
        r'\begin{tabularx}{\linewidth}{@{}L{0.44\linewidth}L{0.23\linewidth}Y@{}}',
        r'\toprule Audit window and metric & Measured value & Operational interpretation \\ \midrule',
        f"All-time completed proof contributions & {ga['all_time']['completed_all_time']:,} & {ga['all_time']['merged_all_time']:,} merged ({ga['all_time']['all_time_merge_rate_pct']:.1f}\\%); {ga['all_time']['closed_unmerged_all_time']:,} closed unmerged ({ga['all_time']['all_time_closed_unmerged_rate_pct']:.1f}\\%) before admission " + r'\\',
        f"All-time public preregistration/problem issues & {ga['all_time']['issues_all_time']:,} & {ga['all_time']['issues_closed_all_time']:,} closed; {ga['all_time']['open_current']} active open PRs at snapshot " + r'\\',
        f"Recent consecutive window (22--27 Nov 2026) & {ga['recent_1000_sample']['n']:,} completed PRs & {ga['recent_1000_sample']['merged']} merged ({ga['recent_1000_sample']['merge_rate_pct']:.1f}\\%); {ga['recent_1000_sample']['closed_unmerged']} closed unmerged ({ga['recent_1000_sample']['closed_unmerged_rate_pct']:.1f}\\%, median {ga['recent_1000_sample']['closed_unmerged_median_commits']} commits / {ga['recent_1000_sample']['closed_unmerged_median_additions']} lines attempted) " + r'\\',
        f"Multi-commit repair under automated gates & {ga['recent_1000_sample']['multi_commit_merged_count']}/{ga['recent_1000_sample']['merged']} ({ga['recent_1000_sample']['multi_commit_revision_rate_pct']:.1f}\\%) & Merged PRs requiring iterative repair commits after initial submission " + r'\\',
        f"Admission latency and contribution size & {ga['recent_1000_sample']['median_time_to_merge_min']:.1f} min median & 75th percentile {ga['recent_1000_sample']['p75_time_to_merge_min']:.1f} min; median {ga['recent_1000_sample']['median_additions_merged']} added lines across {ga['recent_1000_sample']['median_changed_files_merged']} files " + r'\\',
        f"Issue linkage and escape-witness metadata & {ga['recent_1000_sample']['prereg_or_issue_linked_pct']:.1f}\\% / {ga['recent_1000_sample']['escape_or_witness_mentioned_pct']:.1f}\\% & {ga['recent_1000_sample']['prereg_or_issue_linked_merged_count']}/{ga['recent_1000_sample']['merged']} cite public issues; {ga['recent_1000_sample']['escape_or_witness_mentioned_merged_count']}/{ga['recent_1000_sample']['merged']} explicitly reference escape-witness criteria " + r'\\',
        r'\bottomrule\end{tabularx}',
        r'\end{table}',
    ]
    (ROOT / 'paper/ablation-table.tex').write_text('\n'.join(t4) + '\n')
    print('Rendered N=30 three-family table/figure and mechanistic ablation + public gate audit table.')


if __name__ == '__main__':
    main()
